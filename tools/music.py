#!/usr/bin/env python3
"""
music.py - the music and the sound effects of Tilomat for the Game Boy's sound chip.

The music is ten songs written by tools/compose.py into tools/songs.json; the player picks one
in the game (SELECT).

Channels: 1 the melody, 2 the second voice, 3 (wave) the bass, 4 (noise) the drums. The
effects take channel 1 from the lead while they play; an effect with noise borrows channel 4.

Output: gen/music.c, gen/music.h

Usage: tools/music.py <gen dir>
"""
import json
import os
import sys

OUT = sys.argv[1] if len(sys.argv) > 1 else 'gen'
A4 = 69

c = ['/* generated by tools/music.py */', '#include "music.h"', '']
h = ['/* generated by tools/music.py */', '#ifndef MUSIC_H', '#define MUSIC_H', '#include <stdint.h>', '']


def table(name, values, typ='uint8_t'):
    c.append('const %s %s[%d] = {' % (typ, name, len(values)))
    for i in range(0, len(values), 16):
        c.append('    ' + ','.join(str(v) for v in values[i:i + 16]) + ',')
    c.append('};')
    h.append('extern const %s %s[%d];' % (typ, name, len(values)))


def note_hz(n):
    return 440.0 * 2 ** ((n - 69) / 12)


def pulse_x(f):
    """The 11 bit frequency value of the pulse channels for f Hz."""
    return max(0, min(2047, int(round(2048 - 131072 / f))))


def wave_x(f):
    return max(0, min(2047, int(round(2048 - 65536 / f))))


# frequencies of the MIDI notes 24..107 (index n - 24)
table('note_pulse', [pulse_x(note_hz(n)) for n in range(24, 108)], 'uint16_t')
table('note_wave', [wave_x(note_hz(n)) for n in range(24, 108)], 'uint16_t')

# ---------------------------------------------------------------- music

with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'songs.json')) as f:
    songs = json.load(f)

# The songs are stored in bars: every channel has a table of one-bar patterns (16 bytes, one per
# 16th: a MIDI note where a note starts, 1 where it ends, 0 while it holds), shared by all songs,
# and every song lists the pattern of each bar, per channel. The songs repeat their bars a lot,
# so this takes about a third of the room of the plain notes.
CHANNELS = ('lead', 'harm', 'bass', 'drum')
patterns = {ch: [] for ch in CHANNELS}
info = []
for i, song in enumerate(songs):
    bars = len(song['bass']) // 16
    order = []
    for ch in CHANNELS:
        for bar in range(bars):
            pat = song[ch][bar * 16:bar * 16 + 16]
            if pat not in patterns[ch]:
                patterns[ch].append(pat)
            order.append(patterns[ch].index(pat))
    table('song_%d' % i, order)
    info.append('    {song_%d, %d, %d, 0x%02x, 0x%02x, 0x%02x, 0x%02x},' % (
        i, bars, song['step_fp'], song.get('lead_duty', 0x80), song.get('lead_env', 0xb5),
        song.get('harm_duty', 0x40), song.get('harm_env', 0x74)))
for ch in CHANNELS:
    assert len(patterns[ch]) <= 256, ch
    table('pat_' + ch, sum(patterns[ch], []))
h += ['', 'typedef struct {', '    const uint8_t *order;   /* the pattern of every bar: lead, harm, bass, drum */',
      '    uint8_t bars;', '    uint16_t step_fp;       /* 1/256 frames per 16th */',
      '    uint8_t lead_duty, lead_env, harm_duty, harm_env;', '} SongInfo;', '',
      '#define SONGS %d' % len(songs), 'extern const SongInfo songs[SONGS];']
c.append('const SongInfo songs[SONGS] = {')
c += info
c.append('};')

# ---------------------------------------------------------------- effects

# commands of an effect program
VOL, DUTY, NOTE, SLIDE, NOISE, OFF, END = 1, 2, 3, 5, 6, 7, 0
effects = {}


def vol(v):
    """The volume envelope (NR12/NR42) for the following notes."""
    return [VOL, v]


def duty(d):
    return [DUTY, d << 6]


def note(n, ticks):
    x = pulse_x(note_hz(n))
    return [NOTE, x >> 8, x & 255, ticks]


def freq(f, ticks):
    x = pulse_x(f)
    return [NOTE, x >> 8, x & 255, ticks]


def slide(f0, f1, ticks):
    a, b = pulse_x(f0), pulse_x(f1)
    return [SLIDE, a >> 8, a & 255, b >> 8, b & 255, ticks]


def noise(level, ticks):
    """Noise: level 0 (highest) .. 7 (lowest)."""
    return [NOISE, (level << 4) | 1, ticks]


def off(ticks):
    return [OFF, ticks]


def arp(notes, ticks):
    return sum((note(n, ticks) for n in notes), [])


DECAY_FAST, DECAY, DECAY_SLOW = 0xf1, 0xf3, 0xf5
effects['MOVE'] = vol(0x50) + duty(2) + freq(1500, 1) + off(1)
effects['CATCH'] = vol(DECAY_FAST) + duty(2) + note(A4 + 7, 2) + note(A4 + 12, 4) + off(1)
effects['DROP'] = vol(DECAY_FAST) + duty(1) + slide(500, 180, 5) + off(1)
effects['LAND'] = vol(0x81) + noise(5, 2) + off(1)
effects['TOSS'] = vol(0xa0) + duty(2) + slide(300, 1200, 6) + off(1)
effects['SPAWN'] = vol(0x30) + duty(0) + freq(900, 1) + freq(1100, 1) + off(1)
effects['BREAK'] = (vol(0xf2) + noise(1, 3) + noise(0, 3) + noise(2, 4) + vol(DECAY_SLOW) + duty(2)
                    + slide(400, 90, 14) + off(4))
effects['WARN'] = vol(0xa0) + duty(2) + note(A4 + 15, 6) + off(4) + note(A4 + 15, 6) + off(4)
effects['DENY'] = vol(0xa0) + duty(2) + freq(196, 3) + freq(185, 4) + off(2)
effects['LINE'] = vol(DECAY) + duty(2) + arp([A4 + 3, A4 + 7, A4 + 12], 3) + note(A4 + 15, 10) + off(2)
effects['LINE_BIG'] = (vol(DECAY_SLOW) + duty(2) + arp([A4, A4 + 3, A4 + 7, A4 + 12, A4 + 15, A4 + 19], 3)
                       + note(A4 + 24, 16) + off(3))
effects['CHAIN'] = (vol(DECAY_SLOW) + duty(1) + arp([A4 + 12, A4 + 15, A4 + 19, A4 + 24], 2)
                    + arp([A4 + 15, A4 + 19, A4 + 24, A4 + 27], 2) + note(A4 + 31, 14) + off(3))
effects['SHIFT_START'] = (vol(0xa0) + duty(2) + freq(880, 6) + off(4) + freq(880, 6) + off(4) + freq(1320, 14)
                          + off(4))
fan = [A4, A4 + 4, A4 + 7, A4 + 12, None, A4 + 7, A4 + 12]
seq = vol(0xa0) + duty(2)
for i, n in enumerate(fan):
    seq += off(5) if n is None else note(n, 16 if i == len(fan) - 1 else 4) + off(1)
effects['SHIFT_DONE'] = seq + vol(DECAY) + duty(1) + arp([A4 + 24, A4 + 28], 3) + note(A4 + 31, 20) + off(4)
effects['GAME_OVER'] = (vol(0xa0) + duty(2) + note(A4 + 7, 12) + note(A4 + 6, 12) + note(A4 + 5, 12)
                        + slide(note_hz(A4 + 4), 90, 60) + off(20))
effects['PAUSE'] = vol(0xa0) + duty(2) + note(A4 + 7, 4) + note(A4, 4) + off(3)
effects['KEY'] = vol(0x60) + duty(1) + note(A4 + 12, 2) + off(1)

names = list(effects)
# a new effect interrupts the one playing only if it is at least as important
PRIO = {'MOVE': 1, 'SPAWN': 0, 'LAND': 1, 'CATCH': 2, 'DROP': 2, 'TOSS': 2, 'DENY': 2, 'BREAK': 4, 'WARN': 4,
        'LINE': 3, 'LINE_BIG': 4, 'CHAIN': 4, 'SHIFT_DONE': 5, 'GAME_OVER': 5}
table('sfx_prio', [0] + [PRIO.get(n, 3) for n in names])
for i, n in enumerate(names):
    h.append('#define SFX_%s %d' % (n, i + 1))
    c.append('static const uint8_t sfx_%d[] = {%s};' % (i, ','.join(str(v) for v in effects[n] + [END])))
c.append('const uint8_t * const sfx_programs[%d] = {%s};' % (len(names), ','.join('sfx_%d' % i
                                                                                 for i in range(len(names)))))
h.append('extern const uint8_t * const sfx_programs[%d];' % len(names))
for k, v in (('VOL', VOL), ('DUTY', DUTY), ('NOTE', NOTE), ('SLIDE', SLIDE), ('NOISE', NOISE), ('OFF', OFF),
             ('END', END)):
    h.append('#define SC_%s %d' % (k, v))
h += ['', '#endif']

os.makedirs(OUT, exist_ok=True)
with open(os.path.join(OUT, 'music.c'), 'w') as f:
    f.write('\n'.join(c) + '\n')
with open(os.path.join(OUT, 'music.h'), 'w') as f:
    f.write('\n'.join(h) + '\n')
print('%d effects' % len(names))
